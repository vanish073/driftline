#!/usr/bin/env python3
"""Per-type auto-resolution share from a simulator campaign's raw output (Shift 8 Prove; README numbers rule).

    python3 scripts/resolution-share.py docs/results/sim-campaign-pr-10k-shift8.txt > docs/results/auto-resolution-shift8.md

Reads the campaign totals `resolution.<TYPE>.<STATE> = N`: the state of every break at the end of each seed's run
(Simulation's end-state stats). For each type it reports how many breaks were closed without a person, split into
RESOLVED_AUTO (Driftline acted: a refund, a confirmed late success, an itemised short line posted as fees),
SELF_HEALED (the late evidence arrived and closed it) and LINKED (it followed the payment's action-owner break, D11);
how many were ESCALATED to a person; and how many were still open when the run ended. Shares are of all breaks of the
type, rounded to one decimal. Only the standard library; the output is deterministic for a given input.
"""
import re
import sys

ONE_TO_ONE = ["DEBITED_NO_ORDER", "LATE_SUCCESS", "DUPLICATE_CAPTURE", "SHORT_SETTLEMENT", "MISSING_SETTLEMENT",
              "ORPHAN_SETTLEMENT"]
AUTO = ["RESOLVED_AUTO", "SELF_HEALED", "LINKED"]
OPEN = ["DETECTED", "AWAITING_EVIDENCE", "ACTION_PENDING"]
LINE = re.compile(r"^\s*resolution\.([A-Z_]+)\.([A-Z_]+) = (\d+)\s*$")


def share(n, total):
    return "%.1f%%" % (100.0 * n / total) if total else "-"


def main(path):
    counts = {}
    header = []
    with open(path, encoding="utf-8") as f:
        for raw in f:
            if raw.startswith("# ") and len(header) < 3:
                header.append(raw[2:].strip())
            m = LINE.match(raw)
            if m:
                counts.setdefault(m.group(1), {})[m.group(2)] = int(m.group(3))
    if not counts:
        sys.exit("no resolution.* totals in " + path)
    others = sorted(t for t in counts if t not in ONE_TO_ONE)
    print("# Auto-resolution share per break type (Shift 8)")
    print()
    print("Generated by `python3 scripts/resolution-share.py %s` from the campaign's raw totals." % path)
    for h in header:
        print("- " + h)
    print("- Each break counted once, in its state when its seed's run ended. *Closed without a person* = "
          "RESOLVED_AUTO + SELF_HEALED + LINKED.")
    print()
    print("| Type | Breaks | Closed without a person | RESOLVED_AUTO | SELF_HEALED | LINKED | ESCALATED | Still open |")
    print("|---|---:|---:|---:|---:|---:|---:|---:|")
    for t in [t for t in ONE_TO_ONE if t in counts] + others:
        c = counts[t]
        total = sum(c.values())
        auto = sum(c.get(s, 0) for s in AUTO)
        still_open = sum(c.get(s, 0) for s in OPEN)
        print("| %s%s | %d | %s | %s | %s | %s | %s | %s |" % (
            t, "" if t in ONE_TO_ONE else " (anomaly)", total, share(auto, total),
            share(c.get("RESOLVED_AUTO", 0), total), share(c.get("SELF_HEALED", 0), total),
            share(c.get("LINKED", 0), total), share(c.get("ESCALATED", 0), total), share(still_open, total)))
    unknown = sorted({s for c in counts.values() for s in c} - set(AUTO) - set(OPEN) - {"ESCALATED"})
    if unknown:
        sys.exit("unexpected states: " + ", ".join(unknown))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
