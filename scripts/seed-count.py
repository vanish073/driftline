#!/usr/bin/env python3
"""Adds up campaign summaries into the cumulative seed count (DESIGN §17 "the cumulative seed count from CI artifacts";
D85). Run by scripts/seed-count.sh, which downloads the artifacts.

    python3 seed-count.py RUNS_JSON ARTIFACT_DIR LOCAL_DIR OUT_JSON OUT_MD

RUNS_JSON lists the GitHub runs (id, workflow, date, commit, branch, event, conclusion); ARTIFACT_DIR/<run id>/<artifact
name>/summary.json holds each shard's summary; LOCAL_DIR/*.json holds the summaries of local campaigns, committed. A
seed counts once: two summaries that cover the same profile and seed range are an error, not a double count. Only
campaign seeds count (fresh seeds without a planted bug); corpus replays, double-runs and canary seeds do not.
"""
import glob
import json
import os
import sys


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main(argv):
    runs_path, artifacts, local_dir, out_json, out_md = argv[1:6]
    runs = {str(r["databaseId"]): r for r in load(runs_path)}
    rows = []
    # gh extracts each artifact into its own directory, or a lone match straight into the run's directory
    found = [(p, p.split(os.sep)[-3], p.split(os.sep)[-2])
             for p in glob.glob(os.path.join(artifacts, "*", "*", "summary.json"))]
    found += [(p, p.split(os.sep)[-2], "sim-summary") for p in glob.glob(os.path.join(artifacts, "*", "summary.json"))]
    for path, run_id, artifact in sorted(found):
        s = load(path)
        r = runs.get(run_id, {})
        rows.append(dict(s, source="github", run_id=run_id, workflow=r.get("workflowName", ""),
                         date=r.get("createdAt", ""), branch=r.get("headBranch", ""), event=r.get("event", ""),
                         artifact=artifact))
    for path in sorted(glob.glob(os.path.join(local_dir, "*.json"))):
        s = load(path)
        rows.append(dict(s, source="local", run_id="", workflow="", date=s.get("finished_at", ""), branch="", event="",
                         artifact=os.path.basename(path)))
    seen = {}
    for row in rows:
        if row["seeds"] == 0:
            continue
        key = (row["profile"], row["first_seed"], row["last_seed"])
        if key in seen:
            sys.exit("the same seeds counted twice: %s in %s and %s" % (key, seen[key], row["artifact"]))
        seen[key] = row["artifact"]
    by_profile = {}
    for row in rows:
        by_profile.setdefault(row["profile"], []).append((row["first_seed"], row["last_seed"], row["artifact"]))
    for profile, ranges in by_profile.items():
        ranges.sort()
        for (a0, a1, an), (b0, b1, bn) in zip(ranges, ranges[1:]):
            if b0 <= a1:
                sys.exit("overlapping %s seed ranges: %s and %s" % (profile, an, bn))
    totals = {}
    for row in rows:
        t = totals.setdefault(row["profile"], {"seeds": 0, "failed_seeds": 0})
        t["seeds"] += row["seeds"]
        t["failed_seeds"] += row["failed_seeds"]
    total = sum(t["seeds"] for t in totals.values())
    failed = sum(t["failed_seeds"] for t in totals.values())
    with open(out_json, "w", encoding="utf-8", newline="\n") as f:
        json.dump({"total_seeds": total, "failed_seeds": failed, "by_profile": totals, "summaries": rows}, f,
                  indent=2, sort_keys=True)
        f.write("\n")
    lines = ["# Cumulative simulator seed count", "",
             "Generated by `scripts/seed-count.sh` from each campaign shard's summary (CI artifacts, and the committed",
             "local summaries in `docs/results/sim-summaries/`). Campaign seeds only: fresh seeds with no planted bug.",
             "Each seed with a violation names itself in its job's log and trace artifact, and is accounted for either",
             "as a real bug (a `docs/BUGS.md` row and a regression seed) or as a modelling or oracle error (a DESIGN",
             "§19 decision, no BUGS row); the Commit column says which code each shard ran.",
             "", "| Profile | Seeds | Seeds with a violation |", "|---|---:|---:|"]
    for profile in sorted(totals):
        lines.append("| %s | %d | %d |" % (profile, totals[profile]["seeds"], totals[profile]["failed_seeds"]))
    lines.append("| **total** | **%d** | **%d** |" % (total, failed))
    lines += ["", "| Where | Workflow | Date | Branch | Commit | Profile | Seeds | Failed | Seed range |",
              "|---|---|---|---|---|---|---:|---:|---|"]
    for row in sorted(rows, key=lambda r: (r["date"], r["artifact"])):
        where = "run %s (%s)" % (row["run_id"], row["artifact"]) if row["source"] == "github" else "local (%s)" % row["artifact"]
        lines.append("| %s | %s | %s | %s | %s | %s | %d | %d | %d..%d |" % (
            where, row["workflow"], row["date"], row["branch"], (row.get("commit") or "")[:7], row["profile"],
            row["seeds"], row["failed_seeds"], row["first_seed"], row["last_seed"]))
    with open(out_md, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines[:11 + len(totals)]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
