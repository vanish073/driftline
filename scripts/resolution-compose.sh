#!/usr/bin/env bash
# The auto-resolution share per break type, measured on the Compose stack (DESIGN §17, method (b); D85).
#
#   scripts/resolution-compose.sh [N] [out-dir]     N breaks injected per type (default 20); out-dir default docs/results
#
# 1. Builds, generates a fresh merchant pool (12 merchants, worlds in the past as the e2e suite's, D51), starts the
#    Compose `core` profile.
# 2. For each one-to-one break type, asks the sandbox to play N of that scenario on its own merchant
#    (`sandbox inject --type T --count N`); the sandbox answers with the breaks Driftline must now show.
# 3. scripts/resolution-compose.py polls the ops CSV export until every expected break of each type exists and no state
#    has changed for 3 minutes, or 15 minutes pass, and writes the share of each type closed without a person
#    (RESOLVED_AUTO, SELF_HEALED, LINKED), escalated (with the reasons) and still open.
# 4. Writes auto-resolution-compose.md (the table, with its header) and auto-resolution-compose.json (the counts); the
#    teardown saves the Compose logs, runs scripts/pii-scan.sh and removes the stack.
# Close VS Code first on the 4 GB laptop.
set -euo pipefail
cd "$(dirname "$0")/.."

N=${1:-20}
OUTDIR=${2:-docs/results}
DEV=deploy/compose/.dev
COMPOSE=(docker compose -f deploy/compose/compose.yaml --env-file "$DEV/env" --profile core)
TYPES=(DEBITED_NO_ORDER LATE_SUCCESS DUPLICATE_CAPTURE SHORT_SETTLEMENT MISSING_SETTLEMENT ORPHAN_SETTLEMENT)
# shellcheck source=lib/compose-stack.sh
. scripts/lib/compose-stack.sh

mkdir -p "$OUTDIR"
work=$(mktemp -d)
header=$(stack_header scripts/resolution-compose.sh "Compose profile core; $N breaks injected per type")
stack_build
stack_secrets 12
on_exit() {
    local status=$?
    set +e
    rm -rf "$work"
    (exit "$status")
    stack_teardown
}
trap on_exit EXIT
stack_up

echo "{" > "$work/expected.json"
first=1
for t in "${TYPES[@]}"; do
    report=$(JAVA_OPTS="$(stack_tls_java)" sandbox/build/install/sandbox/bin/sandbox inject --type "$t" --count "$N" \
        --sandbox https://127.0.0.1:8085)
    echo "inject $t: $report"
    entry=$(python3 -I -c '
import json, sys
r = json.loads(sys.argv[1]); t = sys.argv[2]
keys = [k for k in r["expected_breaks"].split(";") if k]
print(json.dumps({"merchant": r["merchant_id"], "injected": r["count"],
                  "expected": sum(1 for k in keys if k.split(" ")[0] == t),
                  "expected_other_types": sorted({k.split(" ")[0] for k in keys} - {t})}))
' "$report" "$t")
    [ "$first" = 1 ] || echo "," >> "$work/expected.json"
    first=0
    printf '"%s": %s\n' "$t" "$entry" >> "$work/expected.json"
done
echo "}" >> "$work/expected.json"

status=0
python3 scripts/resolution-compose.py "$DEV/bootstrap.json" "$work/expected.json" "$work/table.md" \
    "$OUTDIR/auto-resolution-compose.json" https://127.0.0.1:8080 900 || status=$?
{
    echo "# Auto-resolution share per break type, on the Compose stack"
    echo
    echo "Generated by \`scripts/resolution-compose.sh $N\` (DESIGN §17 method (b), D85)."
    echo "$header" | sed 's/^# /- /'
    echo "- Each type was played on its own merchant by the sandbox's world models, worlds in the past, no faults (D51)."
    echo "  Each break is counted once, in its state once every expected break existed and no state had changed for 3"
    echo "  minutes. *Closed without a person* = RESOLVED_AUTO + SELF_HEALED + LINKED. Worlds in the past (D51) put"
    echo "  deadlines counted from the payment's date close or past on arrival, which the simulation does not."
    echo
    cat "$work/table.md"
} > "$OUTDIR/auto-resolution-compose.md"
cat "$OUTDIR/auto-resolution-compose.md"
exit "$status"
